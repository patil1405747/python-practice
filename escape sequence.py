#Escape sequences
#escape sequence is a backslash used to include special character,like a new line \n.or tab \t inside a string
#\n-->used to insert new line
print("hello\nworld")  

#\t-->used to insert tab space
print("hello\tworld")

#\\-->used to insert backslash inside a string
print("c:\\python\\files")

#\'-->used to insert single quote inside a single quote string
print("It\'s a python class")

#\"-->it used to insert double quote inside a double quote string
print("hi harry,\"heelo\"")

#\b-->It is used to insert backslash character
print("hell\bo")

#r-->it used to skip first world
print("hello\rworld")